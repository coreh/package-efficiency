// Installs TanStack Start in a work folder, builds the application for
// production once (again only when the sources or the installed versions
// change) and starts the built server inside the shared JavaScript runner.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { cpSync, existsSync, readdirSync, readFileSync, rmSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const SOURCES = ['package.json', 'tsconfig.json', 'vite.config.ts', 'adapter.js', 'src']
const PACKAGES = ['@tanstack/react-start', '@tanstack/react-router', 'react', 'react-dom', 'vite', '@vitejs/plugin-react', 'nitro']

// The tuned forms of the application. vite.config.ts reads the name from
// BENCH_VARIANT when it builds, and each form is built into a folder of its
// own (BENCH_OUTPUT), so that one does not overwrite another.
const VARIANTS = { 'compressed-assets': { output: '.output-compressed-assets' } }

function hashInto(hash, file) {
  if (readdirSafe(file)) for (const name of readdirSafe(file).sort()) hashInto(hash, path.join(file, name))
  else hash.update(path.relative(here, file)).update(readFileSync(file))
}
const readdirSafe = (file) => {
  try {
    return readdirSync(file)
  } catch {
    return null
  }
}

export async function prepare({ runtime, variant, helpers }) {
  if (variant && !VARIANTS[variant]) throw new Error(`@tanstack/react-start has no variant named ${variant}`)
  const output = variant ? VARIANTS[variant].output : '.output'
  // Always set, so that a value in the caller's environment cannot choose the form.
  const variantEnv = { BENCH_VARIANT: variant ?? '', BENCH_OUTPUT: output }

  const workdir = helpers.fromRoot('.cache/work/web-application-frameworks/_shared/npm/@tanstack/react-start')
  mkdirSync(workdir, { recursive: true })
  rmSync(path.join(workdir, 'src'), { recursive: true, force: true })
  for (const name of SOURCES) cpSync(path.join(here, name), path.join(workdir, name), { recursive: true })
  // The route tree is generated by the build; it is not part of the sources.
  const versions = await helpers.installPinned(workdir, PACKAGES)
  copyFileSync(helpers.jsRunner, path.join(workdir, 'runner.mjs'))

  // The lockfile stands for every package the named ones bring with them
  // (h3 and srvx among them).
  const hash = createHash('sha256').update(JSON.stringify({ ...versions, variant })).update(readFileSync(path.join(workdir, 'package-lock.json')))
  for (const name of SOURCES) hashInto(hash, path.join(here, name))
  const digest = hash.digest('hex')
  const stamp = path.join(workdir, variant ? `.build-hash-${variant}` : '.build-hash')
  const built = existsSync(path.join(workdir, output, 'server/index.mjs')) && existsSync(stamp) && readFileSync(stamp, 'utf8') === digest
  if (!built) {
    // The stamp goes first: a build that fails must not leave an older one accepted.
    rmSync(stamp, { force: true })
    rmSync(path.join(workdir, output), { recursive: true, force: true })
    // The build is a tool run once; it runs on Node whatever runtime serves it.
    execFileSync(process.execPath, [path.join(workdir, 'node_modules/vite/bin/vite.js'), 'build'], { cwd: workdir, env: { ...process.env, NODE_ENV: 'production', ...variantEnv }, stdio: ['ignore', 'pipe', 'pipe'] })
    if (!existsSync(path.join(workdir, output, 'server/index.mjs'))) throw new Error(`the build did not write ${output}/server/index.mjs`)
    writeFileSync(stamp, digest)
  }

  const { '@tanstack/react-start': version, ...dependencies } = versions
  // Nitro and the packages under it that serve the requests are pre-releases;
  // their versions are recorded with the result.
  for (const name of ['h3', 'srvx']) {
    const nested = path.join(workdir, 'node_modules/nitro/node_modules', name, 'package.json')
    const file = existsSync(nested) ? nested : path.join(workdir, 'node_modules', name, 'package.json')
    if (existsSync(file)) dependencies[name] = JSON.parse(readFileSync(file, 'utf8')).version
  }
  return {
    version,
    dependencies,
    install: helpers.nodeInstall(workdir),
    launch: { command: runtime.bin, args: [...runtime.args, 'runner.mjs', 'adapter.js'], cwd: workdir, env: { NODE_ENV: 'production', ...variantEnv }, phases: ['boot', 'loaded', 'ready'] },
  }
}
